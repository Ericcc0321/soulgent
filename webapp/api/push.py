"""Web Push: subscriptions live in /state/push.json (atomic writes); sending uses pywebpush. Test pushes are not followed by a recall.
Each subscription records its account (admin / a guest account) and sends are split by account; old subscriptions without an account count as admin.
How a guest's account is stored is decided by labels (older deployments with GUEST_LEGACY_ACCOUNT set keep the legacy name, see guestcfg.store_id); the legacy name is then read back as guest too.
Several guests (accounts = admin + every configured guest). A subscription whose account is set but not configured (a guest removed
from .env, an unknown name) is an orphan: it belongs to nobody and is never sent to — in particular it is never treated as admin."""
import hashlib
import json
import os
import re
import sys
import tempfile
import threading
import time
from typing import Any, Callable, Dict, List, Optional
from urllib.parse import urlsplit

try:
    from api import guestcfg, notify
except ImportError:  # in the container the contents of api/ sit directly in the working directory
    import guestcfg  # type: ignore
    import notify  # type: ignore

TTL = 60
MAX_SUBS = 20        # admin: at most this many devices
GUEST_MAX_SUBS = 5   # per guest: at most this many devices (counted per account, so one guest cannot fill the site; admin quota is unaffected)
# Send only to these browser push services (anti-SSRF: guest-registered endpoints are requested by the api). Host name matches exactly or ends with ".suffix"
PUSH_HOSTS = ("fcm.googleapis.com", "android.googleapis.com", "push.apple.com",
              "push.services.mozilla.com", "notify.windows.com")
ACCOUNTS = ("admin", guestcfg.ACCOUNT)  # default account set (when no accounts given); with multiple guests the server passes it in
RECALL_DELAY = 8.0
# Title and body are filled by notify.localize per subscription language (i18n=test); the Simplified Chinese here is only a fallback
TEST_SHOW = {"kind": "show", "tag": "zbs-test", "title": "Soulgent 测试",
             "body": "这是一条测试通知", "url": "/", "i18n": "test"}
TEST_RECALL = {"kind": "recall", "tag": "zbs-test"}

# A subscription stores device info: dev is a random id generated by the page itself, plat the platform, standalone whether it is a home-screen / Dock app.
# Allowlist validation; invalid fields are dropped (the subscription is still accepted); the full UA is not stored
PLATS = ("iphone", "ipad", "mac", "windows", "android", "other")
_DEV_RE = re.compile(r"^[A-Za-z0-9_-]{8,40}$")
# Dead-subscription cleanup: from pruneSince (top level of push.json = the moment cleanup first ran; not reset on restart), a subscription that has not registered device info for this long is dead.
# devSince (the moment of the first subscription) is kept but unused: the clock starts at pruneSince, 14 days
DEAD_AFTER = 14 * 86400
_META = ("devSince", "pruneSince")  # top-level times in push.json to keep besides subscriptions


def device_key(endpoint: Any) -> str:
    """Opaque id in the device list (first 16 chars of the endpoint sha256): deletion matches on it, so the endpoint is never returned to the frontend; old subscriptions without dev can still be deleted."""
    return hashlib.sha256(str(endpoint).encode("utf-8")).hexdigest()[:16]


def clean_device(data: Any) -> Dict[str, Any]:
    if not isinstance(data, dict):
        return {}
    out = {}  # type: Dict[str, Any]
    dev = data.get("dev")
    if isinstance(dev, str) and _DEV_RE.match(dev):
        out["dev"] = dev
    if data.get("plat") in PLATS:
        out["plat"] = data["plat"]
    if isinstance(data.get("standalone"), bool):
        out["standalone"] = data["standalone"]
    return out


def is_apple(endpoint: Any) -> bool:
    """Apple web push (iPhone / iPad home-screen app, Mac Safari / Dock web app): ignores icon and always shows the app icon."""
    try:
        host = urlsplit(str(endpoint)).hostname or ""
    except ValueError:
        return False
    return host == "push.apple.com" or host.endswith(".push.apple.com")


def push_host_ok(endpoint: str) -> bool:
    """Whether the endpoint is a known push service: https, no credentials, default port, host name in PUSH_HOSTS (or a subdomain)."""
    try:
        u = urlsplit(endpoint)
        host = (u.hostname or "").lower()
        port = u.port
    except ValueError:
        return False
    if u.scheme != "https" or "@" in u.netloc or port not in (None, 443):
        return False
    return any(host == h or host.endswith("." + h) for h in PUSH_HOSTS)


def clean_subscription(data: Any) -> Optional[Dict[str, Any]]:
    """Keep only endpoint and keys; None if the format is wrong or the push service is unknown."""
    if not isinstance(data, dict):
        return None
    ep = data.get("endpoint")
    keys = data.get("keys")
    if not isinstance(ep, str) or not ep.startswith("https://") or len(ep) > 2048 or not push_host_ok(ep):
        return None
    if not isinstance(keys, dict):
        return None
    p256dh, auth = keys.get("p256dh"), keys.get("auth")
    if not (isinstance(p256dh, str) and isinstance(auth, str) and p256dh and auth):
        return None
    if len(p256dh) > 256 or len(auth) > 64:
        return None
    return {"endpoint": ep, "keys": {"p256dh": p256dh, "auth": auth}}


def _webpush(sub: Dict[str, Any], payload: Dict[str, Any], private_key: str, subject: str) -> int:
    """Actually send one; returns the HTTP status code, 0 on network failure. pywebpush is loaded lazily (local tests may run without it)."""
    from pywebpush import WebPushException, webpush  # type: ignore
    try:
        r = webpush(sub, json.dumps(payload, ensure_ascii=False), vapid_private_key=private_key,
                    vapid_claims={"sub": subject}, ttl=TTL, headers={"Urgency": "high"}, timeout=10)
        return int(getattr(r, "status_code", 201))
    except WebPushException as e:
        resp = getattr(e, "response", None)
        return int(getattr(resp, "status_code", 0) or 0)
    except Exception:
        return 0


class Push:
    def __init__(self, path: str, sender: Optional[Callable[..., int]] = None,
                 recall_delay: float = RECALL_DELAY, labels: Optional[Dict[str, str]] = None,
                 accounts: Optional[Any] = None, fps: Optional[Dict[str, str]] = None) -> None:
        self.path = path
        # account -> current fingerprint (server.push_fp: login key, plus the bound session for guests). Recorded at subscription time; subscriptions that no longer match are not pushed and are deleted.
        # Old subscriptions without fp are not adopted (and are deleted); the frontend re-registers them with a fingerprint
        self.fps = dict(fps or {})
        self.labels = dict(labels or {})  # account name -> account as stored in push.json (the account name itself if absent)
        # Known accounts: admin + each guest (default admin/guest + those in labels if none given)
        acc = list(accounts) if accounts is not None else list(ACCOUNTS) + list(self.labels)
        self.accounts = tuple(dict.fromkeys(["admin"] + [a for a in acc if isinstance(a, str) and a]))
        self._rev = {v: k for k, v in self.labels.items() if k in self.accounts}  # stored name -> account name
        self.sender = sender or _webpush
        self.recall_delay = recall_delay
        self._lock = threading.Lock()

    # ---- config (from .env) ----
    @staticmethod
    def public_key() -> str:
        return os.environ.get("VAPID_PUBLIC_KEY", "")

    @staticmethod
    def _private_key() -> str:
        return os.environ.get("VAPID_PRIVATE_KEY", "")

    @staticmethod
    def _subject() -> str:
        # The contact address comes only from .env; the default is a placeholder email (no personal email hard-coded)
        return os.environ.get("VAPID_SUBJECT") or "mailto:admin@example.com"

    # ---- storage ----
    def _load_doc(self) -> Dict[str, Any]:
        try:
            with open(self.path, "r", encoding="utf-8") as f:
                data = json.load(f)
        except (OSError, ValueError):
            return {}
        return data if isinstance(data, dict) else {}

    def _load(self) -> List[Dict[str, Any]]:
        subs = self._load_doc().get("subscriptions")
        return [s for s in (subs if isinstance(subs, list) else []) if clean_subscription(s)]

    def _save(self, subs: List[Dict[str, Any]], since: Any = None, **meta: Any) -> None:
        """Write subscriptions back; top-level devSince / pruneSince keep their existing file values if not given."""
        old = self._load_doc()
        if since is not None:
            meta["devSince"] = since
        doc = {"subscriptions": subs}  # type: Dict[str, Any]
        for k in _META:
            v = meta.get(k, old.get(k))
            if isinstance(v, (int, float)) and not isinstance(v, bool):
                doc[k] = v
        d = os.path.dirname(os.path.abspath(self.path))
        os.makedirs(d, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=d, prefix=".push-")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                json.dump(doc, f, ensure_ascii=False)
            os.replace(tmp, self.path)
        except BaseException:
            try:
                os.unlink(tmp)
            except OSError:
                pass
            raise

    @staticmethod
    def account_of(sub: Dict[str, Any], accounts: Any = ACCOUNTS, rev: Optional[Dict[str, str]] = None) -> str:
        """Which account a subscription belongs to: no account (the earliest subscriptions) or admin -> admin; stored name / legacy name -> the matching guest;
        an account that is set but unknown -> returned as is (orphan, nobody is sent to; not defaulted to admin, so a deleted guest never receives admin pushes)."""
        raw = sub.get("account")
        if raw is None or raw == "" or raw == "admin":
            return "admin"
        if not isinstance(raw, str):
            return "?"
        if rev and raw in rev:
            return rev[raw]
        acc = guestcfg.normalize_account(raw)  # legacy-deployment guest subscriptions are recognized too
        return acc if acc in accounts else raw

    def _acc(self, sub: Dict[str, Any]) -> str:
        return self.account_of(sub, self.accounts, self._rev)

    def subscribe(self, sub: Dict[str, Any], account: str = "admin", lang: Any = None,
                  device: Any = None, now: Optional[float] = None) -> bool:
        """Deduplicate by endpoint (the newer one wins for the same endpoint, including a change of login account, UI language or device info). Returns False if over the limit.
        lang (en / hans / hant) is stored with the subscription and picks the push wording; unknown or missing is not stored (Simplified Chinese is used).
        device (dev / plat / standalone, filtered by clean_device) is stored together with the registration time at; devSince is recorded at the first subscription."""
        t = time.time() if now is None else now
        with self._lock:
            doc = self._load_doc()
            # Other endpoints stay; orphan subscriptions (account no longer in the config) are cleaned up on the way, so they take no quota
            subs = [s for s in self._load() if s["endpoint"] != sub["endpoint"] and self._acc(s) in self.accounts]
            if account not in self.accounts:  # unknown accounts are not registered (no fallback to admin)
                return False
            cap = MAX_SUBS if account == "admin" else GUEST_MAX_SUBS
            if sum(1 for s in subs if self._acc(s) == account) >= cap:
                return False
            acc = account
            ent = dict(sub, account=self.labels.get(acc, acc))
            if self.fps.get(acc):
                ent["fp"] = self.fps[acc]
            if isinstance(lang, str) and lang in notify.PUSH_LANGS:
                ent["lang"] = lang
            ent.update(clean_device(device))
            ent["at"] = int(t)
            subs.append(ent)
            since = doc.get("devSince")
            self._save(subs, since if isinstance(since, (int, float)) else t)
            return True

    def devices(self, account: str = "admin") -> List[Dict[str, Any]]:
        """This account's subscriptions (sanitized: no endpoint / keys), used by "notification settings" to show this device, the count and the device list.
        Each item carries key (device_key, used for deletion)."""
        out = []
        for s in self.subscriptions():
            if self._acc(s) != account:
                continue
            d = clean_device(s)
            if isinstance(s.get("at"), (int, float)):
                d["at"] = s["at"]
            d["key"] = device_key(s["endpoint"])
            out.append(d)
        return out

    def remove_device(self, account: str, key: str) -> bool:
        """Manually delete a device: only subscriptions of this account whose key matches (a guest cannot delete admin's, nor vice versa). Returns True if one was deleted."""
        with self._lock:
            subs = self._load()
            keep = [s for s in subs if not (self._acc(s) == account and device_key(s["endpoint"]) == key)]
            if len(keep) == len(subs):
                return False
            self._save(keep)
            return True

    def prune_dead(self, now: Optional[float] = None) -> int:
        """Dead-subscription cleanup: from pruneSince (the moment of the first call, stored in push.json), subscriptions that have not registered device info
        (no dev) for DEAD_AFTER are deleted; returns how many. The first call only records pruneSince.
        Sending / subscribing do not call it; api/server.py notify_round calls it once a day."""
        t = time.time() if now is None else now
        with self._lock:
            doc = self._load_doc()
            subs = self._load()
            since = doc.get("pruneSince")
            if not isinstance(since, (int, float)) or isinstance(since, bool):
                self._save(subs, pruneSince=t)
                return 0
            if t - since < DEAD_AFTER:
                return 0
            keep = [s for s in subs if isinstance(s.get("dev"), str) and s["dev"]]
            if len(keep) != len(subs):
                self._save(keep)
            return len(subs) - len(keep)

    def _live(self, account: str) -> List[Dict[str, Any]]:
        """Subscriptions of this account whose fingerprint matches the current one. Mismatches (key changed / session rebound) and old subscriptions without fingerprint are deleted and not pushed;
        on every start the frontend re-registers the same endpoint with the current fingerprint."""
        fp = self.fps.get(account)
        with self._lock:
            subs = self._load()
            mine = [s for s in subs if self._acc(s) == account]
            if not fp:
                return mine
            stale = [s["endpoint"] for s in mine if s.get("fp") != fp]
            if stale:
                self._save([s for s in subs if s["endpoint"] not in stale])
            return [s for s in mine if s["endpoint"] not in stale]

    def subscriptions(self) -> List[Dict[str, Any]]:
        with self._lock:
            return self._load()

    def _remove(self, endpoints: List[str]) -> None:
        if not endpoints:
            return
        with self._lock:
            self._save([s for s in self._load() if s["endpoint"] not in endpoints])

    # ---- sending ----
    def send_all(self, payload: Dict[str, Any], account: str = "admin") -> Dict[str, int]:
        """Send only to this account's subscriptions. The session avatar av goes only to non-Apple endpoints (Apple ignores icon)."""
        subs = self._live(account)
        sent = failed = 0
        gone = []  # type: List[str]
        for s in subs:
            body = notify.localize(payload, s.get("lang"), not is_apple(s["endpoint"]))
            code = self.sender(s, body, self._private_key(), self._subject())
            if 200 <= code < 300:
                sent += 1
            else:
                failed += 1
                if code in (404, 410):
                    gone.append(s["endpoint"])
        self._remove(gone)
        return {"subscriptions": len(subs), "sent": sent, "failed": failed, "removed": len(gone)}

    def send_test(self, account: str = "admin") -> Dict[str, Any]:
        out = dict(self.send_all(TEST_SHOW, account))  # type: Dict[str, Any]
        return out

    def _recall(self, account: str = "admin") -> None:
        try:
            r = self.send_all(TEST_RECALL, account)
            sys.stderr.write("push recall %s\n" % json.dumps(r))
        except Exception as e:  # a background thread must not raise
            sys.stderr.write("push recall error %s\n" % type(e).__name__)
